import ExcelJS from "exceljs";
import path from "path";
import fs from "fs";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function createTemplate() {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "Gharmai Kirana";
  workbook.lastModifiedBy = "Gharmai Kirana";
  workbook.created = new Date();
  workbook.modified = new Date();

  // 1. Products Sheet (Header Only)
  const sheet = workbook.addWorksheet("Products", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  const columns = [
    { header: "Product Name *", key: "name", width: 34 },
    { header: "Category *", key: "category", width: 22 },
    { header: "Brand", key: "brand", width: 18 },
    { header: "Unit (e.g. 1 kg, 500 g, 1 L) *", key: "unit", width: 26 },
    { header: "MRP (Rs.) *", key: "mrp", width: 16 },
    { header: "Selling Price (Rs.) *", key: "price", width: 20 },
    { header: "Cost Price (Rs.)", key: "purchasePrice", width: 18 },
    { header: "Stock Quantity", key: "stock", width: 16 },
    { header: "Description", key: "description", width: 36 },
    { header: "Image URL", key: "image", width: 30 },
    { header: "Supplier", key: "supplier", width: 20 },
    { header: "Batch Number", key: "batch", width: 18 },
    { header: "Expiry Date (YYYY-MM-DD)", key: "expiryDate", width: 26 },
    { header: "Active (TRUE/FALSE)", key: "active", width: 20 },
    { header: "Featured (TRUE/FALSE)", key: "featured", width: 22 },
    { header: "Best Seller (TRUE/FALSE)", key: "bestSeller", width: 24 },
  ];

  sheet.columns = columns;

  // Style Header Row
  const headerRow = sheet.getRow(1);
  headerRow.height = 30;
  headerRow.eachCell((cell) => {
    cell.font = {
      name: "Calibri",
      size: 11,
      bold: true,
      color: { argb: "FFFFFFFF" },
    };
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF2C5E3B" }, // Forest emerald brand color
    };
    cell.alignment = {
      vertical: "middle",
      horizontal: "center",
      wrapText: true,
    };
    cell.border = {
      top: { style: "thin", color: { argb: "FF1D4028" } },
      bottom: { style: "medium", color: { argb: "FF1D4028" } },
      left: { style: "thin", color: { argb: "FFC4D6CC" } },
      right: { style: "thin", color: { argb: "FFC4D6CC" } },
    };
  });

  // 2. Reference & Instructions Sheet
  const refSheet = workbook.addWorksheet("Categories & Instructions");
  refSheet.columns = [
    { header: "Available Categories in Store", key: "cat", width: 30 },
    { header: "Instructions / Guidelines", key: "notes", width: 50 },
  ];

  const categories = [
    "Rice & Grains",
    "Dal & Pulses",
    "Oil & Ghee",
    "Sugar, Salt & Atta",
    "Spices & Masala",
    "Snacks & Biscuits",
    "Noodles & Pasta",
    "Tea & Coffee",
    "Beverages",
    "Dairy & Eggs",
    "Cleaning Products",
    "Personal Care",
    "Baby Products",
    "Household",
  ];

  const guidelines = [
    "Columns with an asterisk (*) are mandatory.",
    "Category name must match one of the available categories on the left.",
    "Unit examples: '1 kg', '500 g', '1 L', '2 L', '1 pc', 'Pack of 3'.",
    "Prices should be positive numbers in Nepalese Rupees (e.g. 195, 250.5).",
    "Selling Price must be less than or equal to MRP.",
    "Cost Price is optional (for calculating your profit margins).",
    "Stock Quantity is the initial units available in inventory (e.g. 50, 100).",
    "Expiry Date format: YYYY-MM-DD (e.g. 2027-12-31). Leave blank if not perishable.",
    "Active, Featured, Best Seller can be TRUE or FALSE (defaults to TRUE, FALSE, FALSE).",
    "SKU is automatically generated by the system when imported or added.",
  ];

  const maxRows = Math.max(categories.length, guidelines.length);
  for (let i = 0; i < maxRows; i++) {
    refSheet.addRow({
      cat: categories[i] || "",
      notes: guidelines[i] ? `${i + 1}. ${guidelines[i]}` : "",
    });
  }

  const refHeader = refSheet.getRow(1);
  refHeader.height = 26;
  refHeader.eachCell((cell) => {
    cell.font = { name: "Calibri", size: 11, bold: true, color: { argb: "FFFFFFFF" } };
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FFF29C1B" }, // Amber gold accent
    };
    cell.alignment = { vertical: "middle", horizontal: "left" };
  });

  // Target paths
  const rootDir = path.resolve(__dirname, "../../");
  const xlsxPath = path.join(rootDir, "products_template.xlsx");
  const csvPath = path.join(rootDir, "products_template.csv");

  // Save .xlsx file
  await workbook.xlsx.writeFile(xlsxPath);
  console.log(`✅ Created .xlsx file: ${xlsxPath}`);

  // Also write header-only .csv for convenience
  const csvHeader = columns.map((c) => `"${c.header.replace(/"/g, '""')}"`).join(",");
  fs.writeFileSync(csvPath, csvHeader + "\r\n", "utf8");
  console.log(`✅ Created .csv file: ${csvPath}`);
}

createTemplate().catch((err) => {
  console.error("Error creating template:", err);
  process.exit(1);
});
